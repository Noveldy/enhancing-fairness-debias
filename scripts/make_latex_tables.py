"""LaTeX versions of the final summary tables (Phase 9 deliverable), generated from the CSVs only.

    venv/bin/python scripts/make_latex_tables.py

Reads results/summary/*.csv and writes results/summary/latex/*.tex (booktabs; needs \\usepackage{booktabs,
graphicx}). Every number is formatted from the CSV; nothing is typed in. The ablation, fairness-utility and
synthetic tables are written by their own scripts (results/summary/*.tex) and are not repeated here.
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd

REPO_ROOT = Path(__file__).resolve().parents[1]
SUM = REPO_ROOT / "results" / "summary"
OUT = SUM / "latex"


def tex(s) -> str:
    """Escape text for LaTeX; a cell that already contains inline math ($...$) is passed through."""
    s = "" if s is None or (isinstance(s, float) and np.isnan(s)) else str(s)
    if "$" in s:
        return s
    for a, b in (("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"), ("$", r"\$"), ("#", r"\#"),
                 ("_", r"\_"), ("{", r"\{"), ("}", r"\}"), ("~", r"\textasciitilde{}"), ("^", r"\^{}")):
        s = s.replace(a, b)
    return s


def num(x, d=3):
    return "--" if pd.isna(x) else f"{x:.{d}f}"


def mci(m, lo, hi, d=3):
    return "--" if pd.isna(m) else f"{m:.{d}f} [{lo:.{d}f}, {hi:.{d}f}]"


def table(name, df, caption, note, align=None):
    cols = list(df.columns)
    align = align or "l" * 1 + "r" * (len(cols) - 1)
    lines = [f"% generated by scripts/make_latex_tables.py from results/summary/; {note}",
             r"\begin{table}[t]", r"\centering", rf"\caption{{{caption}}}", rf"\label{{tab:{name}}}",
             r"\resizebox{\linewidth}{!}{%", rf"\begin{{tabular}}{{{align}}}", r"\toprule",
             " & ".join(tex(c) for c in cols) + r" \\", r"\midrule"]
    for row in df.itertuples(index=False):
        lines.append(" & ".join(tex(v) for v in row) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}}", r"\end{table}", ""]
    (OUT / f"{name}.tex").write_text("\n".join(lines))
    return name


def read(name):
    return pd.read_csv(SUM / f"{name}.csv", float_precision="round_trip")


def data_summary():
    d = read("data_summary")
    out = pd.DataFrame({
        "dataset": d["dataset"], "rows (all)": d["rows_full"], "rows (complete)": d["rows_baseline"],
        "features": d["n_features"], "target": d["target"],
        "positive rate": d["positive_rate_full"].map(lambda x: num(x, 3)),
        "protected": d["protected_attributes"].fillna("").str.replace(";", ", "),
        "missing cells": d["missing_cells_full"], "rows with missing": d["rows_with_missing_full"]})
    return [table("data_summary", out, "Datasets after loading (all rows and complete rows).", "data_summary.csv")]


BASELINE_METRICS = ["accuracy", "balanced_accuracy", "f1", "roc_auc"]


def baselines():
    b, t = read("baselines_summary"), read("baselines_tests")
    names = []
    for exp, g in b[b["test_rows"] == "complete"].groupby("experiment", sort=False):
        attrs = [a for a in ("sex", "race", "marital") if f"{a}__dp_diff" in set(g["metric"])]
        metrics = BASELINE_METRICS + [f"{a}__{k}" for a in attrs for k in ("dp_diff", "eo_diff")]
        rows = []
        for method, m in g.groupby("method", sort=False):
            m = m.set_index("metric")
            rows.append({"method": method, **{k: mci(*m.loc[k, ["mean", "ci_low", "ci_high"]]) if k in m.index
                                               else "--" for k in metrics}})
        names.append(table(f"baselines_{exp}", pd.DataFrame(rows),
                           f"Baselines vs DBIM, {exp.replace('_', ' ')}: mean [95\\% CI] over 25 outer folds "
                           "(complete test rows; corrected resampled t).", "baselines_summary.csv"))
        tt = t[t["experiment"] == exp]
        rows = [{"comparison": r.comparison, "metric": r.metric,
                 "mean difference [95% CI]": mci(r.mean_diff, r.nb_ci_low, r.nb_ci_high, 4),
                 "p (Holm)": num(r.nb_p_holm, 4), "Wilcoxon p (Holm)": num(r.wilcoxon_p_holm, 4),
                 "d_z": num(r.cohens_dz, 2)} for r in tt.itertuples()]
        names.append(table(f"baselines_tests_{exp}", pd.DataFrame(rows),
                           f"Paired tests DBIM minus baseline, {exp.replace('_', ' ')} (Nadeau--Bengio corrected t, "
                           "Holm within metric).", "baselines_tests.csv", "llrrrr"))
    return names


def timeseries():
    s, t = read("timeseries_summary"), read("timeseries_tests")
    s = s[s["metric"].isin(["test_mae_scaled", "test_smape"])]
    rows = []
    for (scen, h), g in s.groupby(["scenario", "horizon"], sort=False):
        g = g.set_index("metric")
        rows.append({"scenario": scen, "horizon (h)": int(h),
                     "MAE (scaled)": f"{num(g.loc['test_mae_scaled', 'mean_of_fold_means'], 4)} $\\pm$ "
                                     f"{num(g.loc['test_mae_scaled', 'sd_of_fold_means'], 4)}",
                     "SMAPE": f"{num(g.loc['test_smape', 'mean_of_fold_means'], 2)} $\\pm$ "
                              f"{num(g.loc['test_smape', 'sd_of_fold_means'], 2)}"})
    names = [table("timeseries_summary", pd.DataFrame(rows).sort_values(["horizon (h)", "scenario"]),
                   "Air Quality forecasts: mean $\\pm$ SD of the 3 fold means (5 seeds per fold).",
                   "timeseries_summary.csv")]
    rows = [{"comparison": r.comparison, "horizon": int(r.horizon), "metric": r.metric,
             "mean difference [95% CI]": mci(r.mean_diff, r.ci_low, r.ci_high, 4),
             "folds proposed better": f"{int(r.folds_proposed_better)} of 3", "p (Holm)": num(r.t_p_holm, 4)}
            for r in t.itertuples()]
    names.append(table("timeseries_tests", pd.DataFrame(rows),
                       "Air Quality: proposed cleaning minus each alternative (15 fold x seed pairs, not independent; "
                       "see the fold column).", "timeseries_tests.csv", "lrlrrr"))
    return names


def detector():
    i, e = read("detector_internal_cv"), read("detector_external")
    rows = [{"split": r.split, "metric": r.metric, "folds": int(r.n_folds), "mean $\\pm$ SD":
             f"{num(r.mean)} $\\pm$ {num(r.sd)}", "range": f"{num(r.min)}--{num(r.max)}"} for r in i.itertuples()]
    names = [table("detector_internal_cv", pd.DataFrame(rows), "Detector, internal cross-validation "
                   "(grouped by paraphrase cluster, and random).", "detector_internal_cv.csv", "llrrr")]
    e = e[e["dataset"] == "all"]
    rows = [{"method": r.method, "columns": int(r.n), "sensitive": int(r.n_sensitive), "precision": num(r.precision),
             "recall": num(r.recall), "F1": num(r.f1), "false positives": str(r.false_positives).replace(";", ", ")
             if pd.notna(r.false_positives) else "", "missed": str(r.false_negatives).replace(";", ", ")
             if pd.notna(r.false_negatives) else ""} for r in e.itertuples()]
    names.append(table("detector_external", pd.DataFrame(rows), "Detector on the columns of Adult, Bank and German "
                       "Credit (ground truth: the detector's legal list).", "detector_external.csv",
                       "lrrrrrp{3cm}p{5cm}"))
    return names


def cost():
    c, x = read("cost_methods"), read("cost_scaling_exponents")
    rows = [{"dataset": r.dataset, "method": r.name, "model selection (s)": num(r.model_selection_s, 1),
             "final fit (s)": num(r.final_fit_s if pd.notna(r.final_fit_s) else r.fit_and_inference_s, 2),
             "inference (s)": num(r.inference_s, 2), "training total (s)": num(r.total_training_s, 1),
             "vs. none": f"{r.total_vs_none:.1f}$\\times$", "peak memory (GB)": num(r.peak_rss_gb, 2)}
            for r in c.itertuples()]
    names = [table("cost_methods", pd.DataFrame(rows), "Single-core training and inference time (mean of 3 outer "
                   "folds; i5-14500, one thread). Fairness methods: model selection of `none' plus their own fit, "
                   "which includes inference.", "cost_methods.csv", "llrrrrrr")]
    rows = [{"dataset": r.dataset, "component": r.component, "exponent b [95% CI]":
             mci(r.exponent_b, r.exponent_ci_low, r.exponent_ci_high, 2), "local exponents":
             ", ".join(f"{v:.2f}" for v in json.loads(r.local_exponents)),
             "R2 power law": num(r.r2_power_law), "R2 exponential": num(r.r2_exponential),
             "s at 100%": num(r.seconds_at_max, 2)} for r in x.itertuples()]
    names.append(table("cost_scaling_exponents", pd.DataFrame(rows), "Scaling of time with training rows "
                       "(10/25/50/100\\%): log--log slope $b$ (time $\\propto n^b$).", "cost_scaling_exponents.csv",
                       "llrrrrr"))
    return names


def selection():
    s = read("selection_stability")
    rows = [{"experiment": r.experiment, "method": r.method, "distinct choices": int(r.distinct_configs),
             "most frequent (share)": f"{r.most_frequent_config} ({r.most_frequent_share:.2f})",
             "median runner-up gap": num(r.median_runner_up_gap, 4),
             "median within 1 SE": num(r.median_candidates_within_1se, 0),
             "folds with tie across resamplers": num(r.share_folds_with_tie_across_samplers, 2)}
            for r in s.itertuples()]
    return [table("selection_stability", pd.DataFrame(rows), "Stability of the inner-CV selection over 25 outer "
                  "folds.", "selection_stability.csv", "llrp{6cm}rrr")]


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    names = data_summary() + baselines() + timeseries() + detector() + cost() + selection()
    print(f"{len(names)} tables in {OUT.relative_to(REPO_ROOT)}")


if __name__ == "__main__":
    main()
